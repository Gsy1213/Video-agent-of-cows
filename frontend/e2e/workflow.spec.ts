import {test,expect} from '@playwright/test';
import {mkdir,writeFile,readFile} from 'node:fs/promises';

test('上传 → 独立worker → 统计 → seek → RAG引用 → 导出 → 刷新恢复',async({page,request})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 const demo=await request.post('/api/demo');expect(demo.status()).toBe(201);const v=(await demo.json()).data;
 const raw=await request.get(v.media_url);
 await page.goto('/videos');
 await page.getByLabel('上传视频文件').setInputFiles({name:'浏览器上传测试.mp4',mimeType:'video/mp4',buffer:await raw.body()});
 await expect(page.getByText('浏览器上传测试.mp4')).toBeVisible();
 await page.getByLabel('开始分析 浏览器上传测试.mp4').selectOption('normal');
 await expect(page.getByText('有效观察',{exact:true})).toBeVisible();
 await expect(page.getByText('模拟演示',{exact:false}).first()).toBeVisible();
 await expect(page.locator('.metrics strong').nth(0)).toHaveText('100秒');
 await expect(page.locator('.metrics strong').nth(1)).toHaveText('90秒');
 await page.getByLabel('采食片段 20').click();
 await expect.poll(()=>page.locator('video').evaluate(v=>(v as HTMLVideoElement).currentTime)).toBeGreaterThanOrEqual(19.5);
 await page.locator('video').evaluate(v=>(v as HTMLVideoElement).pause());
 const current=await page.locator('video').evaluate(v=>(v as HTMLVideoElement).currentTime);expect(current).toBeLessThan(22);
 await page.getByLabel('开始秒数').fill('25');await page.getByLabel('结束秒数').fill('65');await page.getByRole('button',{name:'应用',exact:true}).click();
 await expect(page.locator('.metrics strong').nth(1)).toHaveText('30秒');
 await expect(page.locator('td').getByText('83.3%',{exact:true})).toBeVisible();
 const analysisUrl=page.url();
 await page.getByRole('link',{name:'养殖知识库'}).click();
 await page.getByRole('button',{name:'上传文档',exact:true}).click();
 await page.locator('input[name=title]').fill('浏览器验收：采食统计口径');
 await page.locator('input[name=source_title]').fill('工程测试原文');
 await page.locator('input[name=is_demo]').check();
 await page.locator('input[name=file]').setInputFiles({name:'口径.md',mimeType:'text/markdown',buffer:Buffer.from('采食占比以已识别行为时长为分母。未知行为和未观察时段不计入分母。工程示例不支持养殖结论。')});
 await page.getByRole('button',{name:'上传并建立索引'}).click();await expect(page.getByText('可检索',{exact:true})).toBeVisible();
 await page.getByLabel('知识检索问题').fill('采食占比如何计算');await page.getByRole('button',{name:'检索',exact:true}).click();
 await expect(page.locator('.retrieval-result')).toBeVisible();
 await page.goto(analysisUrl);await expect(page.getByText('有效观察',{exact:true})).toBeVisible();
 await page.getByLabel('问题',{exact:true}).fill('分析采食情况，给我片段和统计依据');await page.getByRole('button',{name:'发送问题'}).click();
 await expect(page.locator('.fact').filter({hasText:'采食时长'}).getByText('30',{exact:false})).toBeVisible();
 await expect(page.locator('.source-card')).toBeVisible();await page.locator('.source-card').first().click();
 await expect(page.getByRole('dialog',{name:'知识出处'})).toBeVisible();await expect(page.locator('.source-text')).toContainText('已识别行为时长');
 await page.getByRole('button',{name:'关闭',exact:true}).click();
 const downloadPromise=page.waitForEvent('download');await page.getByRole('link',{name:'导出 JSON'}).click();const download=await downloadPromise;expect(download.suggestedFilename()).toMatch(/report-.*\.json/);
 await mkdir('../docs/screenshots',{recursive:true});await download.saveAs('../docs/screenshots/browser-report.json');
 const report=JSON.parse(await readFile('../docs/screenshots/browser-report.json','utf8'));expect(report.statistics[0].classified_duration_s).toBe(90);expect(report.modes.vision).toBe('mock');
 await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:'../docs/screenshots/analysis-1440.png',fullPage:true});
 await page.reload();await expect(page.locator('.fact').filter({hasText:'采食时长'})).toBeVisible();
 await page.setViewportSize({width:1024,height:900});await page.screenshot({path:'../docs/screenshots/analysis-1024.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 expect(errors).toEqual([]);
});

test('历史真实库检索、知识更新删除与失败状态',async({page,request})=>{
 await page.goto('/history');
 await page.getByRole('button',{name:'查询记录',exact:true}).click();
 await expect(page.getByText('来自真实历史库')).toBeVisible({timeout:30000});
 await expect(page.locator('.history-results')).toContainText('2023-07-21');
 await page.screenshot({path:'../docs/screenshots/history.png',fullPage:true});
 const s=(await (await request.post('/api/chat/sessions',{data:{analysis_id:null}})).json()).data;
 const m=await request.post(`/api/chat/sessions/${s.id}/messages`,{data:{client_message_id:'history-e2e',text:'查询1号牛2023-07-25 10:00到10:30的采食事件',selected_track_id:null,range:null}});expect(m.status()).toBe(200);const answer=(await m.json()).data.answer;expect(answer.execution_trace[0].tool).toBe('query_history');expect(answer.history_records[0].label_source).toBe('model_prediction');
 await request.post('/api/knowledge/documents',{multipart:{title:'更新删除独立测试',source_title:'工程验收',is_demo:'true',file:{name:'test.md',mimeType:'text/markdown',buffer:Buffer.from('采食统计原始说明，工程演示。')}}});
 await page.goto('/knowledge');const docRow=page.locator('tr').filter({hasText:'更新删除独立测试'});await expect(docRow.getByText('可检索',{exact:true})).toBeVisible();await docRow.getByRole('button',{name:'查看',exact:true}).click();await expect(page.getByRole('dialog')).toBeVisible();await page.getByRole('button',{name:'关闭',exact:true}).click();
 await docRow.locator('.import-label input').setInputFiles({name:'v2.md',mimeType:'text/markdown',buffer:Buffer.from('新版采食统计：已识别时长作为占比分母，未知和缺测不补齐。')});
 await expect(docRow.locator('td').nth(2)).toContainText('v2');
 await docRow.getByRole('button',{name:'删除',exact:true}).click();await expect(docRow).toHaveCount(0);
 const v=(await (await request.get('/api/videos')).json()).data.items[0];const a=(await (await request.post(`/api/videos/${v.id}/analyses`,{data:{scenario:'provider_failure'}})).json()).data;
 await page.goto(`/videos/${v.id}/analyses/${a.id}`);await expect(page.getByText(/分析失败：/)).toBeVisible();
 await page.screenshot({path:'../docs/screenshots/failure.png',fullPage:true});
 await writeFile('../docs/screenshots/e2e-evidence.json',JSON.stringify({historyMessage:answer,failAnalysis:a.id},null,2));
});
